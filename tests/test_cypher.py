"""The read-only guard and error classifier behind POST /query.

These rules decide what a caller-generated statement may do, so they are pinned
directly rather than only through HTTP: every refusal kind, the literal and
comment blind spots that must *not* trip the guard, and the mapping from an AGE
failure onto the vocabulary a caller's retry loop switches on.

The failure mode of an over-eager scanner is a legitimate query rejected, which
is why the acceptance cases below matter as much as the refusals.
"""

from __future__ import annotations

import pytest
from semantica.utils.exceptions import ProcessingError

from semantica_service.cypher import (
    QueryProblem,
    check_read_only,
    classify_error,
    classify_message,
    normalize_statement,
    strip_literals_and_comments,
)


def refusal(cypher: str) -> QueryProblem:
    """The ``(kind, message)`` a statement is refused with."""
    problem = check_read_only(cypher)
    assert problem is not None, f"expected {cypher!r} to be refused"
    return problem


def kind_of(cypher: str) -> str | None:
    """The refusal kind, or ``None`` when the statement may run."""
    problem = check_read_only(cypher)
    return None if problem is None else problem[0]


# --- accepted statements ---------------------------------------------------


@pytest.mark.parametrize(
    "cypher",
    [
        "MATCH (n) RETURN n",
        "match (n) return n",
        "OPTIONAL MATCH (n) RETURN n",
        "WITH 1 AS x RETURN x",
        "UNWIND [1, 2] AS x RETURN x",
        "RETURN 1 AS one",
        # Leading comments and whitespace are not the statement's first clause.
        "  \n// generated by the caller\n  MATCH (n) RETURN n",
        # A single trailing terminator is allowed.
        "MATCH (n) RETURN n;",
        # Text and punctuation inside literals and comments are not clauses.
        "MATCH (n) RETURN 'delete this' AS note",
        "MATCH (n) WHERE n.x = ';' RETURN n",
        "MATCH (n) /* CREATE (m) DELETE m */ RETURN n",
        "MATCH (n) RETURN n // trailing ; comment",
        # Identifiers that merely contain a keyword must not trip the scan.
        "MATCH (n) RETURN n.name AS settings, n.offset",
        "MATCH (n) WHERE n.deleted_at IS NULL RETURN n",
        # A placeholder is a name, not a clause.
        "MATCH (n) RETURN $created AS c",
        # A list comprehension uses `|` too, but has no label before it.
        "MATCH (n) RETURN [x IN [1, 2] WHERE x > 1] AS xs",
        "MATCH (n)-[r:INTERACTS_WITH]->(m) WHERE n.x = [1, 2] RETURN r",
        # The guard is not a parser: an unclosed literal blanks the rest and AGE's
        # own parser reports the syntax error, which is the honest authority.
        "MATCH (n) WHERE n.name = 'oops RETURN n",
    ],
)
def test_read_only_statements_are_accepted(cypher: str) -> None:
    assert kind_of(cypher) is None


# --- write and admin refusals ----------------------------------------------


@pytest.mark.parametrize(
    "cypher,keyword",
    [
        ("CREATE (n:Drug)", "CREATE"),
        ("MERGE (n:Drug {name: 'x'}) RETURN n", "MERGE"),
        ("MATCH (n) SET n.x = 1 RETURN n", "SET"),
        ("MATCH (n) DELETE n", "DELETE"),
        ("MATCH (a)-[r]->(b) DETACH DELETE a", "DETACH"),
        ("MATCH (n) REMOVE n.x RETURN n", "REMOVE"),
        ("DROP TABLE x", "DROP"),
        ("CALL db.labels()", "CALL"),
        ("COPY (SELECT 1) TO '/tmp/x'", "COPY"),
        ("GRANT ALL ON x TO y", "GRANT"),
        ("REVOKE ALL ON x FROM y", "REVOKE"),
        ("ALTER TABLE x RENAME TO y", "ALTER"),
        ("TRUNCATE x", "TRUNCATE"),
        ("VACUUM FULL", "VACUUM"),
        ("LOAD 'x'", "LOAD"),
    ],
)
def test_write_and_admin_clauses_are_refused(cypher: str, keyword: str) -> None:
    """A write anywhere in the statement is refused, not just at the start."""
    kind, message = refusal(cypher)
    assert kind == "not_read_only"
    assert keyword in message


@pytest.mark.parametrize(
    "cypher", ["EXPLAIN MATCH (n) RETURN n", "SHOW TABLES", "PROFILE RETURN 1"]
)
def test_statements_not_starting_with_a_read_only_clause_are_refused(cypher: str) -> None:
    kind, message = refusal(cypher)
    assert kind == "not_read_only"
    assert "must begin with" in message


def test_a_blank_statement_is_refused() -> None:
    """Whitespace and comments only: there is no statement to validate."""
    assert kind_of("   \n\t") == "not_read_only"
    assert kind_of("// nothing but a comment") == "not_read_only"
    assert kind_of(";") == "not_read_only"


# --- more than one statement -----------------------------------------------


@pytest.mark.parametrize(
    "cypher",
    [
        "MATCH (n) RETURN n; MATCH (m) RETURN m",
        "RETURN 1; RETURN 2;",
        "MATCH (n) RETURN n;;",
        "; MATCH (n) RETURN n",
        "MATCH (n) RETURN n; DROP TABLE x",
    ],
)
def test_more_than_one_statement_is_refused(cypher: str) -> None:
    """A second statement is the more specific diagnosis — and the more
    dangerous one, since it is how a write hides behind a read."""
    assert kind_of(cypher) == "multiple_statements"


# --- constructs that used to be refused on AGE's behalf --------------------


@pytest.mark.parametrize(
    "cypher",
    [
        "MATCH (a), (b) RETURN shortestPath((a)-[*]->(b)) AS p",
        "MATCH (a), (b) RETURN allShortestPaths((a)-[*]->(b)) AS p",
        "MATCH (a)-[r:INTERACTS_WITH|TARGETS]->(c) RETURN r",
        "MATCH (a)-[:TARGETS|BINDS]->(c) RETURN a",
        "MATCH (n) WHERE n.created = datetime() RETURN n",
        "MATCH (n) WHERE n.created > datetime({year: 2020}) RETURN n",
    ],
)
def test_constructs_age_lacked_are_accepted_now(cypher: str) -> None:
    """These were refused because AGE 1.7 could not parse them, not because a
    caller did not want them. Neo4j implements all three, so the guard must let
    them through rather than preserving the limitation the migration removes."""
    assert kind_of(cypher) is None


def test_a_procedure_error_is_still_reported_as_unsupported() -> None:
    """The kind stays in the vocabulary even though nothing AGE-specific
    produces it: it is a client contract, and a genuinely unavailable procedure
    is still an unsupported feature rather than an internal failure."""
    kind, _ = classify_message(
        "{neo4j_code: Neo.ClientError.Procedure.ProcedureNotFound} "
        "{message: There is no procedure with the name `apoc.path.expand`}"
    )
    assert kind == "unsupported_feature"


def test_age_era_limitation_words_are_ordinary_identifiers_now() -> None:
    """`datetime` and `shortestPath` are data or function calls, not refusals."""
    assert kind_of("MATCH (n) WHERE n.note = 'datetime(' RETURN n") is None
    assert kind_of("MATCH (n) RETURN 'shortestPath(x)' AS note") is None


# --- the scan itself -------------------------------------------------------


def test_scan_blanks_literals_and_comments_but_keeps_offsets() -> None:
    """Offsets must survive: ``normalize_statement`` cuts the original at a
    position the scan reported."""
    cypher = "MATCH (n {name: 'x\\'y'}) RETURN n /* DELETE n */ // done"
    scan = strip_literals_and_comments(cypher)

    assert len(scan) == len(cypher)
    assert "x'y" not in scan
    assert "DELETE" not in scan
    assert "done" not in scan
    assert "MATCH" in scan
    assert "RETURN" in scan


def test_scan_keeps_newlines_so_tokens_cannot_merge() -> None:
    cypher = "MATCH (n) // DELETE\nSET"
    scan = strip_literals_and_comments(cypher)
    assert "\n" in scan
    assert "SET" in scan


# --- normalisation ---------------------------------------------------------


def test_normalize_removes_whitespace_and_one_terminator() -> None:
    assert normalize_statement("  MATCH (n) RETURN n;  ") == "MATCH (n) RETURN n"
    assert normalize_statement("MATCH (n) RETURN n") == "MATCH (n) RETURN n"
    assert normalize_statement("MATCH (n) RETURN n; // done") == "MATCH (n) RETURN n"


def test_normalize_keeps_semicolons_inside_literals() -> None:
    assert normalize_statement("MATCH (n) WHERE n.x = ';' RETURN n") == (
        "MATCH (n) WHERE n.x = ';' RETURN n"
    )


# --- error classification --------------------------------------------------


@pytest.mark.parametrize(
    "message,expected",
    [
        (
            "{neo4j_code: Neo.ClientError.Statement.SyntaxError} "
            "{message: Invalid input 'RETURN'}",
            "syntax_error",
        ),
        ("syntax error at or near FOO", "syntax_error"),
        (
            "{neo4j_code: Neo.ClientError.Transaction.TransactionTimedOutClientConfiguration} "
            "{message: The transaction has been terminated.}",
            "timeout",
        ),
        (
            "Query execution failed: transaction timeout after 15000ms",
            "timeout",
        ),
        ("something exploded", "internal"),
    ],
)
def test_classify_message_maps_neo4j_failures(message: str, expected: str) -> None:
    kind, _ = classify_message(message)
    assert kind == expected


def wrapped_store_error(message: str, cause: BaseException | None = None) -> ProcessingError:
    """Rebuild what the store raises: a ``ProcessingError`` whose original error
    (when there is one) stays reachable down the exception chain."""
    try:
        if cause is not None:
            raise cause
        raise RuntimeError(message)
    except BaseException as original:
        try:
            raise ProcessingError(f"Query execution failed: {message}") from original
        except ProcessingError as wrapped:
            return wrapped


def test_classify_error_reads_the_exception_type_chain() -> None:
    """The driver reports a cancelled transaction as ``ClientError`` carrying the
    timeout code, and its message is the signal — the wrapper's type is not."""
    cause = RuntimeError(
        "{neo4j_code: Neo.ClientError.Transaction.TransactionTimedOutClientConfiguration} "
        "{message: The transaction has been terminated.}"
    )
    kind, _ = classify_error(wrapped_store_error("query did not finish", cause=cause))
    assert kind == "timeout"


def test_classify_error_uses_the_innermost_message() -> None:
    """The store's wrapper prefixes the driver's message; the caller wants
    Neo4j's own words rather than the wrapper's."""
    cause = RuntimeError(
        "{neo4j_code: Neo.ClientError.Statement.SyntaxError} "
        "{message: Invalid input 'RETURN' (line 1, column 10)}\n"
        "second line that must not be echoed"
    )
    kind, message = classify_error(wrapped_store_error("Query execution failed", cause=cause))
    assert kind == "syntax_error"
    assert "Invalid input 'RETURN'" in message
    assert "second line" not in message


def test_classify_error_reports_an_unknown_failure_as_internal() -> None:
    kind, message = classify_error(ValueError("something exploded"))
    assert kind == "internal"
    assert "something exploded" in message
    assert "Traceback" not in message


def test_messages_never_carry_credentials() -> None:
    _, message = classify_error(RuntimeError("connect failed: password=hunter2 host=db"))
    assert "hunter2" not in message
    assert "password=***" in message

    _, dsn_message = classify_error(
        RuntimeError("could not connect to postgresql://u:pw@db:5432/x")
    )
    assert "pw@" not in dsn_message
