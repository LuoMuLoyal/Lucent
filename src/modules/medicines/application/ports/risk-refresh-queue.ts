/**
 * 药品风险刷新调度端口（ADR-0025）。
 *
 * 应用层只知道「这个用户的风险评估可能过期了，安排一次重算」，不知道它落在
 * BullMQ 延迟作业、`setTimeout`，还是将来跨进程的消息队列。调度形态是队列
 * 适配器的事。
 *
 * ## 为什么调度语义必须留在端口上
 *
 * 「同一用户的连续变更合并成一次检查」不是实现细节，而是明确的业务权衡：
 * 风险检查便宜（纯静态规则）且时效敏感，所以**不**把截止时间往后推——
 * 检查在突发变更的第一次之后运行。换传输层时这条语义必须原样保留，
 * 否则高频编辑用药的用户可能永远等不到一次检查。
 */

/** 注入令牌。接口在运行时不存在，只有令牌能让 Nest 解析到实现。 */
export const MEDICINE_RISK_REFRESH_QUEUE = Symbol('MedicineRiskRefreshQueue');

/** 风险刷新调度端口。 */
export interface MedicineRiskRefreshQueuePort {
  /**
   * 为 `userId` 安排一次静态风险检查。
   *
   * 实现约定：
   * - **先标记过期再调度**，且标记失败不影响调度——记录必须始终读得出“过期”。
   * - 队列不可用时**退化为同步执行**，不得把异常抛给调用方：调度是性能
   *   优化，不是业务前置条件。
   * - 同一用户的重复调用**不推迟**已排队的检查。
   */
  schedule(userId: string): Promise<void>;
}
