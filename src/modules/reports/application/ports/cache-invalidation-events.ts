/**
 * 报表看板缓存失效端口（ADR-0025）。
 *
 * 应用层只知道「某用户的数据变了，看板缓存需要作废」，不知道这条指令是落在
 * BullMQ 队列、内存内联调用，还是将来某一种跨进程传输（微服务化时的消息
 * 总线）。队列适配器是唯一知道传输形态的地方。
 *
 * ## 为什么端口要包含「消费侧」
 *
 * 这个能力有两个方向：生产者（事件到达）和消费者（真正删缓存）。两者在
 * BullMQ 实现里同属一个服务，但在微服务拆分后可能位于不同进程——生产侧只
 * 负责投递，消费侧只负责删除。端口把**语义**固定下来（「让某用户的看板缓存
 * 失效」），实现可以自由地决定是同进程调用还是跨进程发消息。
 *
 * 传输层的替换**不改变**这条语义：缓存失效是幂等的，可以迟到、可以重试，
 * 且绝不能反过来阻塞写请求。
 */

/** 注入令牌。接口在运行时不存在，只有令牌能让 Nest 解析到实现。 */
export const REPORTS_CACHE_INVALIDATION = Symbol('ReportsCacheInvalidation');

/** 看板缓存失效端口。 */
export interface ReportsCacheInvalidationPort {
  /**
   * 让 `userId` 的看板缓存失效。
   *
   * 实现约定：**不得抛出**。缓存失效是纯加速手段，数据库才是事实来源；
   * 抖动或传输故障只应记录告警，由 TTL 兜底。
   */
  invalidate(userId: string): Promise<void>;
}
